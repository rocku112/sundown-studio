#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
把波段策略的回測結果丟給 quantstats，產出每個策略一份 HTML 績效報告（對照 0050）。

backtest_swing.py 的組合權益只在「出場日」記帳，看不到持有期間的浮動虧損，也算不出
日波動、Sharpe。這裡用同一批交易、同一套滿倉規則（資金分 SLOTS 份、先到先得），
改成逐日按市價計值：

  進場日：開盤價（含手續費、滑價）→ 當日收盤
  持有中：前日收盤 → 當日收盤
  出場日：前日收盤 → 開盤價（扣手續費、證交稅、滑價）

每筆交易逐日報酬連乘後等於 backtest_swing.net_return，成本口徑一致。
組合日報酬 = 當天所有持倉的日報酬總和 ÷ SLOTS（空倉的份數報酬為 0）。

只輸出樣本外期間（與前端「波段」頁一致）；加 --full 則輸出全期間。

輸入：swing/.cache/ohlcv.json（build_ohlcv.py 或 fetch_hist.py 產生）
輸出：twflow/web/reports/swing_<策略>.html

用法：python -X utf8 swing/scripts/report_qs.py [--full]
需要：pip install quantstats
"""

import argparse
import json
import os
import warnings
from collections import defaultdict

import numpy as np
import pandas as pd

import backtest_swing as bs

OUT_DIR = os.path.join(bs.REPO, "twflow", "web", "reports")


def daily_paths(trades, src):
    """每筆交易拆成 {日期: 當日報酬}。"""
    px = {c: {r[0]: (r[1], r[4]) for r in s["rows"]} for c, s in src.items()}
    dates = {c: [r[0] for r in s["rows"]] for c, s in src.items()}
    out = []
    for t in trades:
        p, d = px[t["code"]], dates[t["code"]]
        kind = src[t["code"]]["kind"]
        i0, i1 = d.index(t["in"]), d.index(t["out"])
        path = {d[i0]: p[d[i0]][1] / (p[d[i0]][0] * (1 + bs.FEE + bs.SLIP)) - 1}
        for i in range(i0 + 1, i1):
            path[d[i]] = p[d[i]][1] / p[d[i - 1]][1] - 1
        path[d[i1]] = p[d[i1]][0] * (1 - bs.FEE - bs.TAX[kind] - bs.SLIP) / p[d[i1 - 1]][1] - 1
        out.append(path)
    return out


def taken_trades(trades, start, end):
    """與 backtest_swing.portfolio 相同的滿倉規則，回傳實際進場的交易。"""
    ev = sorted((t for t in trades if start <= t["in"] <= end), key=lambda t: t["in"])
    open_until, taken = [], []
    for t in ev:
        open_until = [x for x in open_until if x > t["in"]]
        if len(open_until) >= bs.SLOTS:
            continue
        open_until.append(t["out"])
        taken.append(t)
    return taken


def portfolio_returns(trades, src, calendar):
    """逐日記帳：進場時投入前日權益的 1/SLOTS（現金不足就投入剩餘現金），持有期間部位市值
    隨個股漲跌，出場日開盤收回現金。回傳組合日報酬。"""
    paths = daily_paths(trades, src)
    enter, leave = defaultdict(list), defaultdict(list)
    for i, t in enumerate(trades):
        enter[t["in"]].append(i)
        leave[t["out"]].append(i)
    cash, pos, prev, out = 1.0, {}, 1.0, {}
    for d in calendar:
        for i in leave[d]:
            cash += pos.pop(i) * (1 + paths[i][d])
        for i in pos:
            pos[i] *= 1 + paths[i].get(d, 0.0)   # 停牌日沒有報價，市值不變
        for i in enter[d]:
            alloc = min(prev / bs.SLOTS, cash)
            cash -= alloc
            pos[i] = alloc * (1 + paths[i][d])
        eq = cash + sum(pos.values())
        out[d] = eq / prev - 1
        prev = eq
    s = pd.Series(out, dtype=float)
    s.index = pd.to_datetime(s.index)
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--full", action="store_true", help="輸出全期間（預設只輸出樣本外）")
    args = ap.parse_args()

    import quantstats as qs
    warnings.filterwarnings("ignore")

    src = json.load(open(bs.SRC, encoding="utf-8"))["symbols"]
    all_dates = sorted({r[0] for s in src.values() for r in s["rows"]})
    split_date = all_dates[int(len(all_dates) * bs.SPLIT)]
    start = all_dates[0] if args.full else split_date
    end = all_dates[-1]
    calendar = [d for d in all_dates if start <= d <= end]

    eligible = bs.eligibility(src, all_dates)
    trades = defaultdict(list)
    for code, sym in src.items():
        a = {k: np.array([r[i] for r in sym["rows"]], float) for k, i in (("c", 4), ("h", 2), ("v", 5))}
        tr, _ = bs.run_symbol(code, sym, bs.make_strategies(a), eligible[code])
        for k, v in tr.items():
            trades[k].extend(v)

    b = src[bs.BENCH]["rows"]
    bench = pd.Series({r[0]: r[4] for r in b}, dtype=float)
    bench.index = pd.to_datetime(bench.index)
    bench = bench.pct_change().reindex(pd.to_datetime(calendar)).fillna(0.0).rename(bs.BENCH)

    meta = bs.make_strategies({"c": np.zeros(1), "h": np.zeros(1), "v": np.zeros(1)})
    os.makedirs(OUT_DIR, exist_ok=True)
    label = "全期間" if args.full else "樣本外"
    for k, trs in trades.items():
        taken = taken_trades(trs, start, end)
        rets = portfolio_returns(taken, src, calendar).rename(k)
        out = os.path.join(OUT_DIR, f"swing_{k}.html")
        title = f"{meta[k]['name']}｜{label} {start}～{end}｜{len(taken)} 筆"
        qs.reports.html(rets, benchmark=bench, output=out, download_filename=os.path.basename(out),
                        title=title, periods_per_year=245)
        with open(out, encoding="utf-8") as f:
            page = f.read()
        with open(out, "w", encoding="utf-8") as f:
            f.write(page.replace("<title>Tearsheet (generated by QuantStats)</title>",
                                 f"<title>{title}</title>", 1))
        total = (1 + rets).prod() - 1
        print(f"{meta[k]['name']:<10} {len(taken):>5} 筆  累積 {total * 100:7.2f}%  "
              f"Sharpe {qs.stats.sharpe(rets, periods=245):5.2f}  MDD {qs.stats.max_drawdown(rets) * 100:6.2f}%  → {out}")


if __name__ == "__main__":
    main()
